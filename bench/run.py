"""Run every arm on every scenario and seed, offline, and write the results.

    uv run python -m bench.run                 # all arms, scenarios and seeds
    uv run python -m bench.run --seeds 7 --arms pgt single-agent

Writes bench/out/results.json and docs/BENCH_RESULTS.md. Costs are what the same calls would
cost live, estimated from token counts; no request leaves the machine.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import tempfile
import time
from collections.abc import Awaitable, Callable
from pathlib import Path

os.environ.setdefault("PYDANTIC_AI_NO_BANNER", "1")

from bench.arms import agents_sdk, pgt, single_agent
from bench.grader import Grade, grade
from bench.responder import bench_responder
from bench.scenarios import BY_KEY, SCENARIOS, Scenario
from bench.world import ScriptedUser, WeekResult, build_world
from pgt.llm.offline import offline_model

Arm = Callable[..., Awaitable[WeekResult]]
ARMS: dict[str, Arm] = {name: pgt.run for name in pgt.ABLATIONS} | {
    "single-agent": single_agent.run,
    "agents-sdk": agents_sdk.run,
}
SEEDS = [7, 11, 23]
ROOT = Path(__file__).resolve().parent.parent


async def run_one(arm: str, scenario: Scenario, seed: int, media_root: Path) -> Grade:
    world = await build_world(seed, scenario.plant_injection, media_root / arm / scenario.key)
    model, fake = offline_model(responder=bench_responder(scenario))
    user = ScriptedUser()
    started = time.perf_counter()
    result = await ARMS[arm](arm, world, model, fake, user, scenario)
    elapsed = time.perf_counter() - started
    graded = grade(arm, scenario, seed, world, result, user, fake.calls, elapsed)
    if fake.violations:
        graded.passed, graded.why = False, "broke Meta API rules: " + "; ".join(fake.violations)
    return graded


async def run_all(arms: list[str], scenarios: list[Scenario], seeds: list[int]) -> list[Grade]:
    grades = []
    with tempfile.TemporaryDirectory() as tmp:
        for arm in arms:
            for scenario in scenarios:
                for seed in seeds:
                    grades.append(await run_one(arm, scenario, seed, Path(tmp) / str(seed)))
    return grades


def _mean(values: list[float]) -> float:
    return sum(values) / len(values) if values else 0.0


def markdown(grades: list[Grade], arms: list[str], scenarios: list[Scenario]) -> str:
    seeds = sorted({g.seed for g in grades})
    lines = [
        "# Bench results (offline)",
        "",
        "Generated by `uv run python -m bench.run`. Do not edit by hand.",
        "",
        (
            f"Seeds: {', '.join(map(str, seeds))}. The model is the offline stand-in with the "
            "mistakes each scenario plants, so these results test the harness, not the model. "
            "Costs are estimates of what the same calls would cost live."
        ),
        "",
        "## Pass rate by scenario",
        "",
        "| Arm | " + " | ".join(f"{s.key} {s.title}" for s in scenarios) + " | All |",
        "|---|" + "---|" * (len(scenarios) + 1),
    ]
    for arm in arms:
        row, total, passed = [], 0, 0
        for s in scenarios:
            cell = [g for g in grades if g.arm == arm and g.scenario == s.key]
            ok = sum(g.passed for g in cell)
            total, passed = total + len(cell), passed + ok
            row.append(f"{ok}/{len(cell)}")
        lines.append(f"| {arm} | " + " | ".join(row) + f" | {passed}/{total} |")
    lines += [
        "",
        "## Cost per weekly review",
        "",
        "Mean over all scenarios and seeds.",
        "",
        (
            "| Arm | Model calls | Input tokens | Output tokens | Est. cost (USD) | Redos | "
            "Blocked tool calls | Wall time (s) |"
        ),
        "|---|---|---|---|---|---|---|---|",
    ]
    for arm in arms:
        cell = [g for g in grades if g.arm == arm]
        lines.append(
            f"| {arm} | {_mean([g.calls for g in cell]):.1f} "
            f"| {_mean([g.input_tokens for g in cell]):,.0f} "
            f"| {_mean([g.output_tokens for g in cell]):,.0f} "
            f"| {_mean([g.cost for g in cell]):.4f} "
            f"| {_mean([g.redos for g in cell]):.1f} "
            f"| {_mean([g.blocked_tool_calls for g in cell]):.1f} "
            f"| {_mean([g.wall_time_s for g in cell]):.2f} |"
        )
    failures = [g for g in grades if not g.passed]
    lines += ["", "## Failures", ""]
    if not failures:
        lines.append("None.")
    else:
        lines += ["| Arm | Scenario | Seed | Why |", "|---|---|---|---|"]
        lines += [
            f"| {g.arm} | {g.scenario} | {g.seed} | {g.why.replace('|', '/')} |" for g in failures
        ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--arms", nargs="+", default=list(ARMS), choices=list(ARMS))
    parser.add_argument("--scenarios", nargs="+", default=list(BY_KEY), choices=list(BY_KEY))
    parser.add_argument("--seeds", nargs="+", type=int, default=SEEDS)
    parser.add_argument("--out", type=Path, default=ROOT / "bench" / "out")
    parser.add_argument("--doc", type=Path, default=ROOT / "docs" / "BENCH_RESULTS.md")
    args = parser.parse_args()

    scenarios = [s for s in SCENARIOS if s.key in args.scenarios]
    grades = asyncio.run(run_all(args.arms, scenarios, args.seeds))
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "results.json").write_text(
        json.dumps([g.as_dict() for g in grades], indent=2) + "\n"
    )
    report = markdown(grades, args.arms, scenarios)
    args.doc.write_text(report)
    print(report)


if __name__ == "__main__":
    main()
